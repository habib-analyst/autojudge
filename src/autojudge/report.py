"""Audit report: a verdict document a human can read and a skeptic can check."""

from __future__ import annotations

from .evaluate import ComparisonResult

_VERDICT_BLURBS = {
    "WIN": (
        "real improvement",
        "System B beats system A and the difference survives all three "
        "gates: it is statistically significant (p < alpha), the bootstrap "
        "confidence interval excludes zero, and the effect size is "
        "practically meaningful (|d| >= d_min). This is a win you can defend.",
    ),
    "REGRESSION": (
        "real regression",
        "System B is significantly and practically WORSE than system A. "
        "Do not ship B.",
    ),
    "NOT_PRACTICALLY_SIGNIFICANT": (
        "statistically detectable but practically meaningless",
        "The difference passes the significance tests, but the effect size "
        "is below the practical threshold (|d| < d_min). A naive "
        "mean-comparison would call this a win; the audit does not. Ship it "
        "only if you can argue the tiny gain is worth the cost.",
    ),
    "NO_SIGNIFICANT_DIFFERENCE": (
        "no significant difference",
        "The audit could not reject the null hypothesis: the observed gap "
        "is consistent with judge/system noise. Treat A and B as tied until "
        "more tasks are collected.",
    ),
}


def render_audit(result: ComparisonResult) -> str:
    a = result.audit
    p_ok, ci_ok, d_ok = a.win_components
    short, blurb = _VERDICT_BLURBS[a.verdict]

    def gate(ok: bool) -> str:
        return "PASS" if ok else "FAIL"

    lines = [
        f"# Improvement audit: {result.name_a} vs {result.name_b}",
        "",
        f"**VERDICT: {a.verdict}** — {short}.",
        "",
        blurb,
        "",
        "## Numbers",
        "",
        "| metric | value |",
        "|---|---|",
        f"| tasks scored | {a.n} |",
        f"| mean({result.name_a}) | {a.mean_a:.4f} |",
        f"| mean({result.name_b}) | {a.mean_b:.4f} |",
        f"| mean difference (B - A) | {a.mean_diff:+.4f} |",
        f"| permutation p-value | {a.p_value:.4f} (alpha = {a.alpha}) |",
        f"| bootstrap 95% CI of mean diff | [{a.ci_lo:+.4f}, {a.ci_hi:+.4f}] |",
        f"| Cohen's d_z | {a.cohens_d:+.4f} (practical bar {a.d_min}) |",
        "",
        "## Gates (all three must pass for a WIN)",
        "",
        f"| gate | result |",
        "|---|---|",
        f"| p < {a.alpha} | {gate(p_ok)} |",
        f"| CI excludes zero | {gate(ci_ok)} |",
        f"| |d| >= {a.d_min} | {gate(d_ok)} |",
        "",
        "## Plain-language read",
        "",
        f"A naive comparison would declare this "
        f"{'a win for B' if a.mean_diff > 0 else 'a win for A' if a.mean_diff < 0 else 'a tie'} "
        f"(mean gap {a.mean_diff:+.4f}). The audit's verdict is **{a.verdict}** "
        f"because " + (
            "all three gates passed."
            if a.verdict in ("WIN", "REGRESSION")
            else "the significance gate did not reject the null."
            if a.verdict == "NO_SIGNIFICANT_DIFFERENCE"
            else "the effect is real but too small to matter."
        ),
        "",
        f"Scoring failures: {result.n_failures} of {result.n_tasks} tasks.",
        "",
        "---",
        "_Generated by autojudge — the judge that refuses to declare a win "
        "until the improvement is statistically real._",
    ]
    return "\n".join(lines)
